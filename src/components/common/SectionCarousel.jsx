import { useCallback, useEffect, useId, useRef, useState } from 'react';
import { Link } from 'react-router-dom';
import { ArrowRight, ChevronLeft, ChevronRight } from 'lucide-react';
import '../../styles/section-carousel.css';

const DEFAULT_COLUMNS = {
  desktop: 8,
  laptop: 6,
  tablet: 5,
  small: 4,
  mobile: 3.2,
};

const DRAG_THRESHOLD = 7;

/**
 * Universal scrollable section for categories, brands, products and collections.
 * Only the item renderer changes; the heading, controls and scrolling stay shared.
 *
 * Example:
 * <SectionCarousel
 *   title="Best Sellers"
 *   items={products}
 *   columns={{ desktop: 5, laptop: 4, tablet: 3, small: 2, mobile: 1.3 }}
 *   renderItem={(product) => <ProductCard product={product} />}
 * />
 */
export default function SectionCarousel({
  title,
  subtitle,
  items = [],
  renderItem,
  getItemKey,
  columns = DEFAULT_COLUMNS,
  gap = 16,
  viewAllHref,
  viewAllLabel = 'View All',
  titleAlign = 'left',
  className = '',
  arrowLabel = 'items',
  showArrows = true,
  arrowsOnHover = false,
  withContainer = true,
  emptyMessage = null,
}) {
  const trackRef = useRef(null);
  const pointerRef = useRef(null);
  const suppressClickRef = useRef(false);
  const resetClickTimerRef = useRef(null);
  const [canPrev, setCanPrev] = useState(false);
  const [canNext, setCanNext] = useState(false);
  const [dragging, setDragging] = useState(false);
  const generatedId = useId();
  const headingId = `jnr-carousel-title-${generatedId.replace(/:/g, '')}`;
  const list = Array.isArray(items) ? items : [];
  const count = list.length;

  const updateEdges = useCallback(() => {
    const track = trackRef.current;
    if (!track) return;
    const maxScroll = Math.max(0, track.scrollWidth - track.clientWidth);
    const previous = track.scrollLeft > 2;
    const next = track.scrollLeft < maxScroll - 2;
    setCanPrev((value) => (value === previous ? value : previous));
    setCanNext((value) => (value === next ? value : next));
  }, []);

  useEffect(() => {
    const track = trackRef.current;
    if (!track) return undefined;

    updateEdges();
    const observer = typeof ResizeObserver !== 'undefined'
      ? new ResizeObserver(updateEdges)
      : null;
    observer?.observe(track);
    window.addEventListener('resize', updateEdges);
    track.addEventListener('scroll', updateEdges, { passive: true });

    return () => {
      observer?.disconnect();
      window.removeEventListener('resize', updateEdges);
      track.removeEventListener('scroll', updateEdges);
    };
  }, [count, updateEdges]);

  useEffect(() => () => {
    if (resetClickTimerRef.current != null) {
      window.clearTimeout(resetClickTimerRef.current);
    }
  }, []);

  const scrollByPage = useCallback((direction) => {
    const track = trackRef.current;
    if (!track) return;
    const reducedMotion = window.matchMedia?.('(prefers-reduced-motion: reduce)')?.matches;
    track.scrollBy({
      left: direction * track.clientWidth * 0.8,
      behavior: reducedMotion ? 'auto' : 'smooth',
    });
  }, []);

  const handlePointerDown = (event) => {
    if (event.pointerType !== 'mouse' || event.button !== 0) return;
    if (resetClickTimerRef.current != null) window.clearTimeout(resetClickTimerRef.current);
    suppressClickRef.current = false;
    const track = trackRef.current;
    if (!track) return;
    pointerRef.current = {
      id: event.pointerId,
      startX: event.clientX,
      startScroll: track.scrollLeft,
      moved: false,
    };
  };

  const handlePointerMove = (event) => {
    const pointer = pointerRef.current;
    const track = trackRef.current;
    if (!pointer || !track || pointer.id !== event.pointerId) return;
    const delta = event.clientX - pointer.startX;
    if (!pointer.moved && Math.abs(delta) < DRAG_THRESHOLD) return;
    if (!pointer.moved) {
      pointer.moved = true;
      suppressClickRef.current = true;
      setDragging(true);
      try { track.setPointerCapture(event.pointerId); } catch { /* already released */ }
    }
    track.scrollLeft = pointer.startScroll - delta;
  };

  const handlePointerEnd = (event) => {
    const pointer = pointerRef.current;
    if (!pointer || pointer.id !== event.pointerId) return;
    pointerRef.current = null;
    setDragging(false);
    const track = trackRef.current;
    if (track?.hasPointerCapture?.(event.pointerId)) {
      track.releasePointerCapture(event.pointerId);
    }
    // Clear only after the click generated by pointerup has been intercepted.
    if (pointer.moved) {
      resetClickTimerRef.current = window.setTimeout(() => {
        suppressClickRef.current = false;
      }, 0);
    }
  };

  const onKeyDown = (event) => {
    if (event.target !== event.currentTarget) return;
    if (event.key === 'ArrowRight' || event.key === 'ArrowLeft') {
      event.preventDefault();
      scrollByPage(event.key === 'ArrowRight' ? 1 : -1);
    } else if (event.key === 'Home' || event.key === 'End') {
      event.preventDefault();
      trackRef.current?.scrollTo({
        left: event.key === 'Home' ? 0 : trackRef.current.scrollWidth,
        behavior: 'auto',
      });
    }
  };

  const safeColumn = (key) => {
    const value = Number(columns?.[key] ?? DEFAULT_COLUMNS[key]);
    return Number.isFinite(value) && value >= 1 ? value : DEFAULT_COLUMNS[key];
  };

  const cssVars = {
    '--jnr-carousel-desktop': safeColumn('desktop'),
    '--jnr-carousel-laptop': safeColumn('laptop'),
    '--jnr-carousel-tablet': safeColumn('tablet'),
    '--jnr-carousel-small': safeColumn('small'),
    '--jnr-carousel-mobile': safeColumn('mobile'),
    '--jnr-carousel-gap': `${Math.max(0, Number(gap) || 0)}px`,
  };

  if (!count && !emptyMessage) return null;

  return (
    <section
      className={[
        'jnr-carousel-section',
        withContainer && 'container',
        titleAlign === 'center' && 'jnr-carousel-section--center-title',
        arrowsOnHover && 'jnr-carousel-section--hover-arrows',
        className,
      ].filter(Boolean).join(' ')}
      style={cssVars}
      aria-labelledby={title ? headingId : undefined}
      aria-label={!title ? 'Featured collections' : undefined}
    >
      {(title || subtitle || viewAllHref) && (
        <div className="jnr-carousel-header">
          <div className="jnr-carousel-heading">
            {title && <h2 id={headingId} className="jnr-carousel-title">{title}</h2>}
            {subtitle && <p className="jnr-carousel-subtitle">{subtitle}</p>}
          </div>
          {viewAllHref && (
            <Link className="jnr-carousel-view-all" to={viewAllHref}>
              {viewAllLabel} <ArrowRight size={16} aria-hidden="true" />
            </Link>
          )}
        </div>
      )}

      {count ? (
        <div className="jnr-carousel-frame">
          {showArrows && (
            <button
              type="button"
              className="jnr-carousel-arrow jnr-carousel-arrow--prev"
              aria-label={`Previous ${arrowLabel}`}
              aria-controls={headingId + '-track'}
              onClick={() => scrollByPage(-1)}
              disabled={!canPrev}
            >
              <ChevronLeft size={20} aria-hidden="true" />
            </button>
          )}
          <div
            id={headingId + '-track'}
            ref={trackRef}
            className={`jnr-carousel-track${dragging ? ' is-dragging' : ''}`}
            role="region"
            aria-roledescription="carousel"
            aria-label={`${title || 'Collection'} — scrollable items`}
            tabIndex={0}
            onKeyDown={onKeyDown}
            onPointerDown={handlePointerDown}
            onPointerMove={handlePointerMove}
            onPointerUp={handlePointerEnd}
            onPointerCancel={handlePointerEnd}
            onLostPointerCapture={() => {
              pointerRef.current = null;
              setDragging(false);
            }}
            onDragStart={(event) => event.preventDefault()}
            onClickCapture={(event) => {
              if (suppressClickRef.current) {
                event.preventDefault();
                event.stopPropagation();
                suppressClickRef.current = false;
              }
            }}
          >
            {list.map((item, index) => (
              <div
                key={getItemKey ? getItemKey(item, index) : (item?.id ?? item?.slug ?? index)}
                className="jnr-carousel-cell"
                role="group"
                aria-roledescription="slide"
                aria-label={`${index + 1} of ${count}`}
              >
                {renderItem ? renderItem(item, index) : null}
              </div>
            ))}
          </div>
          {showArrows && (
            <button
              type="button"
              className="jnr-carousel-arrow jnr-carousel-arrow--next"
              aria-label={`Next ${arrowLabel}`}
              aria-controls={headingId + '-track'}
              onClick={() => scrollByPage(1)}
              disabled={!canNext}
            >
              <ChevronRight size={20} aria-hidden="true" />
            </button>
          )}
        </div>
      ) : (
        <p className="jnr-carousel-empty">{emptyMessage}</p>
      )}
    </section>
  );
}
